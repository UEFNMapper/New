manifest = {}
for key in ORDER:
    dst = os.path.join(OUT, key + ".png")
    if key in PICK:
        base, rel, meta = PICK[key]
        im = square(Image.open(os.path.join(base, rel)))
        im = to_white_alpha(im)
        im.save(dst, optimize=True)
        manifest[key] = {"file": key + ".png", "originalFile": rel, **meta, "size": SIZE}
    else:
        fn, desc = GENERATED[key]
        im = fn()
        im.save(dst, optimize=True)
        manifest[key] = {"file": key + ".png", "originalFile": None, **GEN, "notes": desc, "size": SIZE}
    print(key, os.path.getsize(dst))

json.dump(manifest, open(os.path.join(OUT, "MANIFEST.json"), "w"), indent=2)

